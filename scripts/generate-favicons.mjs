import sharp from "sharp";
import fs from "fs";
import { join, resolve } from "path";
import { ACCENT, BACKGROUND, BORDER_STRONG } from "../src/lib/tokens.js";
import { isDirectInvocation } from "./lib/direct-invocation.mjs";

// Systems Console EK mark: mirrors the nav masthead monogram (src/App.jsx).
// Paths only, no <text>: SVG favicons cannot load Geist.

export const GRID = 32;
export const ICO_SIZES = [16, 32, 48];

// Glyph geometry on the 32-unit grid (cap height y=9..23, 3-unit stroke).
const E_RECTS = [
  { x: 7, y: 9, w: 3, h: 14 },
  { x: 7, y: 9, w: 8, h: 3 },
  { x: 7, y: 14.5, w: 7, h: 3 },
  { x: 7, y: 20, w: 8, h: 3 },
];
const K_STEM = { x: 17, y: 9, w: 3, h: 14 };
const K_ARMS = "M20 14.2 L23.4 9 H26.8 L22.2 16 L26.8 23 H23.4 L20 17.8 Z";

const ARITY = { M: 2, L: 2, H: 1, V: 1, Z: 0 };

// Absolute M/L/H/V/Z path points, enough for K_ARMS. Throws on anything it would otherwise drop.
export function pathPoints(d) {
  const pts = [];
  let x = 0;
  let y = 0;
  const segments = d.match(/[A-Za-z][^A-Za-z]*/g) ?? [];
  if (segments.join("").length !== d.replace(/^\s+/, "").length) {
    throw new Error(`Unparseable path data: ${d}`);
  }
  for (const seg of segments) {
    const cmd = seg[0];
    if (!(cmd in ARITY)) throw new Error(`Unsupported path command "${cmd}" in: ${d}`);
    const args = seg.slice(1).trim();
    const n = args === "" ? [] : args.split(/[\s,]+/).map(Number);
    if (n.length !== ARITY[cmd] || n.some(Number.isNaN)) {
      throw new Error(`Path command ${cmd} needs exactly ${ARITY[cmd]} number(s), got "${args}"`);
    }
    if (cmd === "Z") continue;
    if (cmd === "H") x = n[0];
    else if (cmd === "V") y = n[0];
    else [x, y] = n;
    pts.push([x, y]);
  }
  return pts;
}

// Unscaled glyph bbox (EK group), derived from the geometry above.
const RAW_BBOX = (() => {
  const xs = [];
  const ys = [];
  for (const r of [...E_RECTS, K_STEM]) {
    xs.push(r.x, r.x + r.w);
    ys.push(r.y, r.y + r.h);
  }
  for (const [px, py] of pathPoints(K_ARMS)) {
    xs.push(px);
    ys.push(py);
  }
  return { x0: Math.min(...xs), y0: Math.min(...ys), x1: Math.max(...xs), y1: Math.max(...ys) };
})();
const RAW_CX = (RAW_BBOX.x0 + RAW_BBOX.x1) / 2;
const RAW_CY = (RAW_BBOX.y0 + RAW_BBOX.y1) / 2;

// Maskable safe zone: centred circle of radius 0.4 x size. Scale leaves headroom inside it.
export const MASKABLE_SCALE = 0.85;

const SCALES = { tile: 1, fullbleed: 1, maskable: MASKABLE_SCALE };

/** Glyph bounding box in output grid units, centred on the tile after the group transform. */
export function glyphBounds(variant = "tile", scale = SCALES[variant]) {
  const hw = ((RAW_BBOX.x1 - RAW_BBOX.x0) / 2) * scale;
  const hh = ((RAW_BBOX.y1 - RAW_BBOX.y0) / 2) * scale;
  const c = GRID / 2;
  return { x0: c - hw, y0: c - hh, x1: c + hw, y1: c + hh, cx: c, cy: c };
}

const num = (n) => String(Number(n.toFixed(3)));
const rect = ({ x, y, w, h }) => `<rect x="${x}" y="${y}" width="${w}" height="${h}"/>`;

export function faviconSvg({ variant = "tile" } = {}) {
  if (!(variant in SCALES)) throw new Error(`Unknown favicon variant: ${variant}`);
  const scale = SCALES[variant];
  const c = GRID / 2;
  const transform = `translate(${c} ${c}) scale(${num(scale)}) translate(${num(-RAW_CX)} ${num(-RAW_CY)})`;
  const base =
    variant === "tile"
      ? `  <rect width="${GRID}" height="${GRID}" rx="4" fill="${BACKGROUND}"/>
  <rect x="1.5" y="1.5" width="29" height="29" rx="3" fill="none" stroke="${BORDER_STRONG}" stroke-width="1"/>`
      : `  <rect width="${GRID}" height="${GRID}" fill="${BACKGROUND}"/>`;

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" width="${GRID}" height="${GRID}">
  <!-- Systems Console EK mark (${variant}); generated by scripts/generate-favicons.mjs -->
${base}
  <g fill="${ACCENT}" transform="${transform}">
    ${E_RECTS.map(rect).join("\n    ")}
    ${rect(K_STEM)}
    <path d="${K_ARMS}"/>
  </g>
</svg>
`;
}

// Dedicated 16px design: integer-only geometry on a 16-unit grid, so 1 unit = 1 px and every
// edge lands on a pixel boundary (the 32-unit mark scaled down blurs at 16px).
export const GRID_16 = 16;

// Glyph pixel map, rows 4-11 and cols 2-13 (centred): E stem + 3 bars, K stem + staircase arms.
export const GLYPH_16 = [
  { x: 2, y: 4, w: 2, h: 8 },
  { x: 4, y: 4, w: 3, h: 2 },
  { x: 4, y: 7, w: 2, h: 2 },
  { x: 4, y: 10, w: 3, h: 2 },
  { x: 8, y: 4, w: 2, h: 8 },
  { x: 12, y: 4, w: 2, h: 1 },
  { x: 11, y: 5, w: 2, h: 1 },
  { x: 10, y: 6, w: 2, h: 1 },
  { x: 10, y: 7, w: 1, h: 2 },
  { x: 10, y: 9, w: 2, h: 1 },
  { x: 11, y: 10, w: 2, h: 1 },
  { x: 12, y: 11, w: 2, h: 1 },
];

export function favicon16Svg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID_16} ${GRID_16}" width="${GRID_16}" height="${GRID_16}">
  <!-- Systems Console EK mark (16px, pixel-snapped); generated by scripts/generate-favicons.mjs -->
  <rect width="${GRID_16}" height="${GRID_16}" rx="2" fill="${BACKGROUND}"/>
  <rect x="0.5" y="0.5" width="15" height="15" rx="1.5" fill="none" stroke="${BORDER_STRONG}" stroke-width="1"/>
  <g fill="${ACCENT}">
    ${GLYPH_16.map(rect).join("\n    ")}
  </g>
</svg>
`;
}

/** Assemble an ICO container from PNG buffers (PNG-compressed entries; sizes read from IHDR). */
export function encodeIco(pngBuffers) {
  const count = pngBuffers.length;
  const dirSize = 6 + 16 * count;
  const header = Buffer.alloc(dirSize);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(count, 4);

  let offset = dirSize;
  pngBuffers.forEach((png, i) => {
    const w = png.readUInt32BE(16);
    const h = png.readUInt32BE(20);
    const e = 6 + 16 * i;
    header.writeUInt8(w >= 256 ? 0 : w, e);
    header.writeUInt8(h >= 256 ? 0 : h, e + 1);
    header.writeUInt8(0, e + 2); // palette colours
    header.writeUInt8(0, e + 3); // reserved
    header.writeUInt16LE(1, e + 4); // planes
    header.writeUInt16LE(32, e + 6); // bpp
    header.writeUInt32LE(png.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += png.length;
  });

  return Buffer.concat([header, ...pngBuffers]);
}

/** Render at native resolution: density maps the `grid`-unit viewBox onto n pixels. */
export function renderPng(svg, n, grid = GRID) {
  return sharp(Buffer.from(svg), { density: (72 * n) / grid })
    .resize(n, n)
    .png()
    .toBuffer();
}

export async function generateFavicons(outDir) {
  fs.mkdirSync(outDir, { recursive: true });
  const tile = faviconSvg({ variant: "tile" });
  const fullbleed = faviconSvg({ variant: "fullbleed" });
  const maskable = faviconSvg({ variant: "maskable" });

  const icoPngs = await Promise.all(
    ICO_SIZES.map((n) => (n === 16 ? renderPng(favicon16Svg(), 16, GRID_16) : renderPng(tile, n))),
  );
  const ico = encodeIco(icoPngs);
  const files = {
    "favicon.svg": tile,
    "favicon.ico": ico,
    "apple-touch-icon.png": await renderPng(fullbleed, 180),
    "icon-192.png": await renderPng(tile, 192),
    "icon-512.png": await renderPng(tile, 512),
    "icon-maskable-512.png": await renderPng(maskable, 512),
  };
  for (const [name, data] of Object.entries(files)) {
    fs.writeFileSync(join(outDir, name), data);
  }
  return Object.keys(files);
}

async function main() {
  const i = process.argv.indexOf("--outDir");
  const value = process.argv[i + 1];
  if (i !== -1 && (!value || value.startsWith("--"))) {
    console.error("--outDir requires a directory argument");
    process.exit(1);
  }
  const outDir = resolve(i !== -1 ? value : "public");
  const written = await generateFavicons(outDir);
  if (process.argv.includes("--previews")) {
    fs.writeFileSync(join(outDir, "preview-16.png"), await renderPng(favicon16Svg(), 16, GRID_16));
    fs.writeFileSync(join(outDir, "preview-32.png"), await renderPng(faviconSvg({ variant: "tile" }), 32));
  }
  console.log(`Wrote ${written.join(", ")} to ${outDir}`);
}

if (isDirectInvocation(process.argv[1], import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
